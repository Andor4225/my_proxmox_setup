#!/bin/bash
# deploy.sh — FAE practice lab deployer. RUNS ON THE PROXMOX HOST.
#
# Design notes:
#  - eth0 (192.168.10.20X) + default route via 192.168.10.1 are the learner's
#    SSH lifeline over Tailscale and are NEVER touched by any fault. eth1 is
#    created with an IP but deliberately NO gateway.
#  - Containers are privileged with nesting=1; lab2 additionally gets
#    /dev/net/tun passthrough (smoke-tested) so OpenVPN can create tun0.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
. "$SCRIPT_DIR/lib/common.sh" || { echo "cannot source lib/common.sh"; exit 1; }

STORAGE="local-lvm"
MGMT_BRIDGE="vmbr0"
# Explicit resolver. WITHOUT this, `pct create` inherits the HOST's
# /etc/resolv.conf — which on this box is generated by Tailscale and points at
# MagicDNS (100.100.100.100). The containers are NOT on the tailnet, so that
# resolver is unreachable: routing works, DNS silently dies, and apt hangs
# forever resolving deb.debian.org. CT 300 (working) uses 8.8.8.8 for the same
# reason. Do not remove.
CT_NAMESERVER="8.8.8.8 1.1.1.1"
DISK_GB=8
MEM_MB=1024
CORES=1
TEMPLATE=""   # resolved at runtime by preflight (D3)

usage() {
  cat <<'USAGE'
FAE practice lab deployer (run on the Proxmox host)

  ./deploy.sh deploy  [lab1|lab2|lab3|lab4|all]   create + configure + arm faults + snapshot
  ./deploy.sh break   [lab1|lab2|lab3|lab4|all]   re-inject faults (no snapshot)
  ./deploy.sh reset   [lab1|lab2|lab3|lab4|all]   roll back to the armed broken state
  ./deploy.sh keys    [lab1|lab2|lab3|lab4|all]   re-seed fae's authorized_keys from the host
  ./deploy.sh status                               containers, snapshot + live fault state
  ./deploy.sh destroy [lab1|lab2|lab3|lab4|all]   remove lab containers

Labs:  lab1 = broken router      (CT 201/202, vmbr1)
       lab2 = tunnel failure     (CT 203/204, vmbr2)
       lab3 = raw log playground (CT 205)
       lab4 = name resolution    (CT 206/207, vmbr3)
USAGE
}

# ORDER IS LOAD-BEARING: rows must stay CTID-ascending so lab2 role 'a' (the
# key generator) is processed before role 'b' (the key consumer). See
# deploy_lab step 2. spec_rows() sorts defensively so a future edit to this
# literal cannot silently break lab2. (M7)
# id|name|lab|role|mgmt_ip|lab_bridge|lab_cidr    ('-' = none)
LAB_SPEC="
201|lab-router-a|lab1|a|192.168.10.201|vmbr1|10.10.10.10/24
202|lab-router-b|lab1|b|192.168.10.202|vmbr1|10.10.10.20/24
203|lab-vpn-a|lab2|a|192.168.10.203|vmbr2|10.20.20.10/24
204|lab-vpn-b|lab2|b|192.168.10.204|vmbr2|10.20.20.20/24
205|lab-logs|lab3|solo|192.168.10.205|-|-
206|lab-dns-a|lab4|a|192.168.10.206|vmbr3|10.40.40.10/24
207|lab-dns-b|lab4|b|192.168.10.207|vmbr3|dhcp
"

lab_dir() {
  case "$1" in
    lab1) echo "$SCRIPT_DIR/lab1-broken-router" ;;
    lab2) echo "$SCRIPT_DIR/lab2-tunnel-failure" ;;
    lab3) echo "$SCRIPT_DIR/lab3-log-playground" ;;
    lab4) echo "$SCRIPT_DIR/lab4-name-resolution" ;;
    *) return 1 ;;
  esac
}

spec_rows() {
  local want="$1"
  printf '%s\n' "$LAB_SPEC" | while IFS='|' read -r id name lab role mgmt br cidr; do
    [ -n "${id:-}" ] || continue
    if [ "$want" = "all" ] || [ "$lab" = "$want" ]; then
      printf '%s|%s|%s|%s|%s|%s|%s\n' "$id" "$name" "$lab" "$role" "$mgmt" "$br" "$cidr"
    fi
  done | sort -t'|' -k1,1n
}

validate_target() {
  case "${1:-}" in
    lab1|lab2|lab3|lab4|all) return 0 ;;
    *) die "target must be one of: lab1 lab2 lab3 lab4 all (got '${1:-<none>}')" ;;
  esac
}

# Only require the bridges the chosen target actually needs; destroy/status
# have no business demanding them at all. (D5)
preflight() {
  local target="${1:-all}" mode="${2:-full}" b need=""
  [ -f /etc/pve/.version ] || die "this must run on the Proxmox host"
  if [ "$mode" = "full" ]; then
    # Resolve the template that actually exists rather than pinning a version
    # that preflight only substring-matched. (D3)
    TEMPLATE="$(pveam list local 2>/dev/null | awk '/debian-12-standard/ {print $1; exit}')"
    [ -n "$TEMPLATE" ] || die "no debian-12-standard template in 'local' — run: pveam available && pveam download local <name>"
    case "$target" in
      lab1) need="vmbr1" ;; lab2) need="vmbr2" ;; lab3) need="" ;; lab4) need="vmbr3" ;;
      all)  need="vmbr1 vmbr2 vmbr3" ;;
    esac
    for b in $need; do
      ip link show "$b" >/dev/null 2>&1 \
        || die "bridge $b missing — create /etc/network/interfaces.d/lab-bridges then 'ifup $b'"
    done
  fi
}

# ---------------- create ----------------
create_ct() {
  local id="$1" name="$2" mgmt="$3" br="$4" cidr="$5" lab="$6" out
  assert_lab_id "$id"; assert_not_protected "$id"

  if ct_exists "$id"; then
    warn "CT $id already exists — skipping create (use 'destroy' first to rebuild)"
    # A partially-created lab2 CT would otherwise be unrepairable by re-running
    # deploy: create_ct returned before ever applying the passthrough. (D9)
    if [ "$lab" = "lab2" ]; then
      add_tun_passthrough "$id" || { err "CT $id: TUN passthrough repair failed"; return 1; }
    fi
    return 0
  fi

  local -a args=(
    "$id" "$TEMPLATE"
    --hostname "$name" --cores "$CORES" --memory "$MEM_MB"
    --rootfs "${STORAGE}:${DISK_GB}"
    --net0 "name=eth0,bridge=${MGMT_BRIDGE},ip=${mgmt}/24,gw=${MGMT_GW}"
    --features nesting=1 --unprivileged 0 --onboot 0
    --nameserver "$CT_NAMESERVER"
  )
  # eth1 carries the lab segment. NOTE: no gw= — a default route on the lab NIC
  # would hijack the mgmt route and sever the learner's SSH.
  if [ "$br" != "-" ] && [ "$cidr" != "-" ]; then
    args+=( --net1 "name=eth1,bridge=${br},ip=${cidr}" )
  fi

  if ! out=$(pct create "${args[@]}" </dev/null 2>&1); then
    err "pct create $id failed: $out"; return 1
  fi

  if [ "$lab" = "lab2" ]; then
    add_tun_passthrough "$id" || { err "CT $id: TUN passthrough failed — OpenVPN cannot work"; return 1; }
  fi
  ok "created CT $id ($name)"
}

# PVE stores snapshots as [snapname] sections AFTER the live config, so a blind
# append would write these keys into a snapshot stanza where they do nothing.
# Insert before the first section header instead. (D4)
add_tun_passthrough() {
  local id="$1" conf="/etc/pve/lxc/${id}.conf" tmp rc=0
  assert_safe_ctid "$id"
  [ -f "$conf" ] || { err "CT $id: config $conf not found"; return 1; }
  grep -q 'devices.allow: c 10:200' "$conf" 2>/dev/null && return 0
  tmp="$(mktemp)" || { err "mktemp failed"; return 1; }
  if ! awk '
    /^\[/ && !done { print "lxc.cgroup2.devices.allow: c 10:200 rwm";
                     print "lxc.mount.entry: /dev/net dev/net none bind,create=dir"; done=1 }
    { print }
    END { if (!done) { print "lxc.cgroup2.devices.allow: c 10:200 rwm";
                       print "lxc.mount.entry: /dev/net dev/net none bind,create=dir" } }
  ' "$conf" > "$tmp"; then
    err "CT $id: awk failed building config — leaving $conf untouched"; rm -f "$tmp"; return 1
  fi
  # Sanity-check the rendered file BEFORE overwriting: /etc/pve is pmxcfs, which
  # does not support rename-based atomic replace, so a bad write truncates the
  # live container config. Refuse to write anything that lost content. (C4)
  if [ ! -s "$tmp" ] || [ "$(wc -l < "$tmp")" -lt "$(wc -l < "$conf")" ]; then
    err "CT $id: rendered config looks truncated — refusing to write"; rm -f "$tmp"; return 1
  fi
  cat "$tmp" > "$conf" || rc=1
  rm -f "$tmp"
  [ "$rc" -eq 0 ] || { err "CT $id: write to $conf failed"; return 1; }
  grep -q 'devices.allow: c 10:200' "$conf" 2>/dev/null     && grep -q 'mount.entry: /dev/net' "$conf" 2>/dev/null     || { err "CT $id: TUN passthrough lines not present after write"; return 1; }
  return 0
}

# ---------------- deploy ----------------
deploy_lab() {
  local target="$1" dir rows id name lab role mgmt br cidr rc=0 failed=""
  rows="$(spec_rows "$target")"

  # 1. create + start.
  while IFS='|' read -r id name lab role mgmt br cidr; do
    [ -n "${id:-}" ] || continue
    if ! create_ct "$id" "$name" "$mgmt" "$br" "$cidr" "$lab"; then
      rc=1; failed="${failed} ${id}"; continue
    fi
    ct_start_wait "$id" || { err "CT $id did not become ready"; rc=1; failed="${failed} ${id}"; }
  done <<< "$rows"

  # 2. run setup.sh per container.
  while IFS='|' read -r id name lab role mgmt br cidr; do
    [ -n "${id:-}" ] || continue
    case " $failed " in *" $id "*) continue ;; esac
    dir="$(lab_dir "$lab")" || { err "unknown lab $lab"; rc=1; continue; }

    # lab3's setup.sh installs and runs the generator from /root/gen-syslog.sh,
    # so the payload MUST be in place BEFORE setup runs. Pushing it afterwards
    # meant lab3 deployed with an empty dataset and no exercise at all. (C1)
    if [ "$lab" = "lab3" ] && [ -f "$dir/gen-syslog.sh" ]; then
      pct push "$id" "$dir/gen-syslog.sh" /root/gen-syslog.sh --perms 755 </dev/null >/dev/null 2>&1 \
        || { err "CT $id gen-syslog.sh push failed"; rc=1; failed="${failed} ${id}"; continue; }
    fi

    # lab2 ordering: the server mints the static key; it must reach the client
    # before the client's setup runs.
    if [ "$lab" = "lab2" ] && [ "$role" = "b" ]; then
      relay_vpn_key || { err "lab2 static key relay failed"; rc=1; failed="${failed} ${id}"; continue; }
    fi

    log "CT $id: running setup.sh ($lab role=$role)"
    if ct_run_script "$id" "$dir/setup.sh" /root/setup.sh "$role"; then
      ok "CT $id setup complete"
    else
      err "CT $id setup FAILED"; rc=1; failed="${failed} ${id}"; continue
    fi

    # The on-disk FIELD_TICKET.txt is AUTHORITATIVE and is installed last, so it
    # overwrites whatever copy setup.sh embedded. Without this, changing a lab's
    # faults ships the previous version's ticket unless the heredoc is edited in
    # lockstep — a drift trap that bit lab1's v2 rebuild.
    if [ -f "$dir/FIELD_TICKET.txt" ]; then
      if pct push "$id" "$dir/FIELD_TICKET.txt" /root/FIELD_TICKET.txt --perms 644 </dev/null >/dev/null 2>&1          && pct exec "$id" -- cp /root/FIELD_TICKET.txt /etc/motd </dev/null >/dev/null 2>&1; then
        ok "CT $id ticket installed from disk (authoritative)"
      else
        warn "CT $id ticket install failed — MOTD may show a stale ticket"
      fi
    fi
  done <<< "$rows"

  # 3. Never arm or snapshot a container whose baseline never built — that
  #    durably bakes a half-configured lab into the reset point. (C6/D10)
  if [ -n "$failed" ]; then
    err "setup failed on CT(s):${failed} — NOT arming or snapshotting '$target'"
    err "fix the errors above, then re-run: $0 deploy $target"
    return 1
  fi

  # Seed SSH keys FROM THE HOST. The container-side setup.sh reads
  # /root/.ssh/authorized_keys, but that path resolves INSIDE the container,
  # where it is empty on a fresh build — so the host's keys never arrived that
  # way and every lab shipped with password-only access. Do it from here, where
  # /root/.ssh/authorized_keys means the host's.
  seed_keys "$target" || warn "key seeding had failures — password fallback (faelab123) still works"

  if break_lab "$target"; then
    snapshot_lab "$target" || rc=1
  else
    err "faults did not arm cleanly for '$target' — NOT snapshotting."
    err "fix the errors above, then: $0 break $target && $0 deploy $target"
    return 1
  fi
  return $rc
}

# Stage the VPN pre-shared key through a private temp file rather than a fixed,
# world-readable path in /tmp. (D2)
relay_vpn_key() {
  local tmp rc=0
  assert_lab_id 203; assert_lab_id 204
  ct_exists 203 || { err "CT 203 (vpn server) missing — cannot relay key"; return 1; }
  tmp="$(mktemp)" || { err "mktemp failed"; return 1; }
  chmod 600 "$tmp"
  if ! pct pull 203 /etc/openvpn/static.key "$tmp" </dev/null >/dev/null 2>&1; then
    err "could not pull static.key from CT 203"; rm -f "$tmp"; return 1
  fi
  if ! pct exec 204 -- mkdir -p /etc/openvpn </dev/null >/dev/null 2>&1; then
    err "could not create /etc/openvpn on CT 204"; rm -f "$tmp"; return 1
  fi
  if ! pct push 204 "$tmp" /etc/openvpn/static.key --perms 600 </dev/null >/dev/null 2>&1; then
    err "could not push static.key to CT 204"; rc=1
  else
    ok "relayed OpenVPN static key 203 -> 204"
  fi
  rm -f "$tmp"
  return $rc
}

# ---------------- keys ----------------
# Lab containers seed fae's authorized_keys at deploy time from the host's root
# keys. Adding a key to the host later (e.g. the Ubuntu travel laptop) would
# otherwise require a full redeploy — this re-seeds in place.
seed_keys() {
  local target="$1" rows id name lab role mgmt rest rc=0 src=/root/.ssh/authorized_keys
  [ -s "$src" ] || die "$src is missing or empty on the host — nothing to seed"
  rows="$(spec_rows "$target")"
  while IFS='|' read -r id name lab role mgmt rest; do
    [ -n "${id:-}" ] || continue
    ct_exists "$id" || { log "CT $id not present — skipping"; continue; }
    ct_running "$id" || { warn "CT $id not running — skipping"; continue; }
    # Treat mkdir/push/chown/chmod as ONE checked sequence: authorized_keys that
    # exists but is root-owned or 0644 is unusable (or insecure) while still
    # reporting [OK]. (D8)
    if pct exec "$id" -- mkdir -p /home/fae/.ssh </dev/null >/dev/null 2>&1        && pct push "$id" "$src" /home/fae/.ssh/authorized_keys --perms 600 </dev/null >/dev/null 2>&1        && pct exec "$id" -- chown -R fae:fae /home/fae/.ssh </dev/null >/dev/null 2>&1        && pct exec "$id" -- chmod 700 /home/fae/.ssh </dev/null >/dev/null 2>&1        && pct exec "$id" -- chmod 600 /home/fae/.ssh/authorized_keys </dev/null >/dev/null 2>&1; then
      ok "CT $id: fae authorized_keys re-seeded ($(grep -c . "$src") keys)"
    else
      err "CT $id: key seeding failed (mkdir/push/chown/chmod)"; rc=1
    fi
  done <<< "$rows"
  return $rc
}

# ---------------- break ----------------
break_lab() {
  local target="$1" rows id name lab role mgmt br cidr dir rc=0
  rows="$(spec_rows "$target")"
  while IFS='|' read -r id name lab role mgmt br cidr; do
    [ -n "${id:-}" ] || continue
    dir="$(lab_dir "$lab")" || continue
    if [ ! -f "$dir/break.sh" ]; then
      log "CT $id ($lab): no break.sh — nothing to arm (by design)"
    else
      log "CT $id: arming faults ($lab role=$role)"
      ct_run_script "$id" "$dir/break.sh" /root/break.sh "$role" \
        && ok "CT $id faults armed" || { err "CT $id break.sh FAILED"; rc=1; }
    fi
    assert_mgmt_intact "$id" "$mgmt" || rc=1
  done <<< "$rows"
  return $rc
}

snapshot_lab() {
  local target="$1" rows id rest rc=0
  rows="$(spec_rows "$target")"
  while IFS='|' read -r id rest; do
    [ -n "${id:-}" ] || continue
    snap_create "$id" && ok "CT $id snapshot '$SNAP_NAME' taken" || rc=1
  done <<< "$rows"
  return $rc
}

# ---------------- reset ----------------
reset_lab() {
  local target="$1" rows id name lab role mgmt rest rc=0
  rows="$(spec_rows "$target")"
  while IFS='|' read -r id name lab role mgmt rest; do
    [ -n "${id:-}" ] || continue
    assert_lab_id "$id"; assert_not_protected "$id"
    log "CT $id: rolling back to '$SNAP_NAME'"
    if snap_rollback "$id"; then
      if ! ct_start_wait "$id"; then
        err "CT $id rolled back but did not start — SSH will not be available"; rc=1; continue
      fi
      # Downgrading this to an "inconclusive" warning meant reset could report
      # success while the learner's only SSH path was gone. (C3)
      if assert_mgmt_intact "$id" "$mgmt"; then
        ok "CT $id reset to armed broken state"
      else
        err "CT $id reset but mgmt path is NOT intact — do not hand this lab out"; rc=1
      fi
    else
      rc=1
    fi
  done <<< "$rows"

  # The lab_armed snapshots are taken during deploy, BEFORE fae's
  # authorized_keys are seeded from the host — so a rollback reverts the
  # container to a state with no SSH keys and silently drops the learner back
  # to password-only auth. Re-seed after every reset so a rollback can never
  # cost you your key.
  seed_keys "$target" || warn "key re-seed after reset had failures — password fallback (faelab123) still works"
  return $rc
}

# ---------------- destroy ----------------
destroy_lab() {
  local target="$1" rows id rest out rc=0
  rows="$(spec_rows "$target")"
  while IFS='|' read -r id rest; do
    [ -n "${id:-}" ] || continue
    assert_lab_id "$id"; assert_not_protected "$id"
    if ct_exists "$id"; then
      # pct stop can return while PVE still holds the config lock, making
      # destroy fail intermittently with the reason swallowed. (D13)
      ct_stop_wait "$id" || warn "CT $id did not stop cleanly — attempting destroy anyway"
      if out=$(pct destroy "$id" --purge </dev/null 2>&1); then ok "destroyed CT $id"
      else err "failed to destroy CT $id: $out"; rc=1; fi
    else
      log "CT $id not present"
    fi
  done <<< "$rows"
  return $rc
}

# ---------------- status ----------------
# SNAP (a reset point exists) and FAULTS (the lab is currently broken) are
# different questions. Reporting only the former showed ARMED=yes even after a
# learner had fixed everything. (D12)
faults_live() {
  local id="$1" lab="$2" role="$3"
  case "${lab}:${role}" in
    # lab1 v2 signatures: tc netem/pfifo qdisc on A, ICMP drop rule on B.
    lab1:a) pct exec "$id" -- tc qdisc show dev eth1 </dev/null 2>/dev/null | grep -qE 'netem|pfifo' ;;
    lab1:b) pct exec "$id" -- bash -c 'nft list ruleset 2>/dev/null | grep -q "echo-request" || iptables -S 2>/dev/null | grep -qi "icmp"' </dev/null 2>/dev/null ;;
    lab2:a) [ "$(pct exec "$id" -- cat /proc/sys/net/ipv4/ip_forward </dev/null 2>/dev/null)" = "0" ] ;;
    lab2:b) pct exec "$id" -- ip link show eth1 </dev/null 2>/dev/null | grep -q 'mtu 1400' ;;
    lab4:a) pct exec "$id" -- bash -c 'grep -rq "^listen-address=127.0.0.1" /etc/dnsmasq.d/ 2>/dev/null' </dev/null 2>/dev/null ;;
    lab4:b) pct exec "$id" -- grep -q 'plant.northstar.example' /etc/hosts </dev/null 2>/dev/null ;;
    *) return 2 ;;   # lab3 has no faults by design
  esac
}

status() {
  printf '\n%-6s %-16s %-6s %-16s %-9s %-6s %-8s %s\n' CTID NAME LAB MGMT_IP STATE SNAP FAULTS MGMT
  printf '%s\n' "--------------------------------------------------------------------------------------------"
  local id name lab role mgmt br cidr st snap fl mg
  while IFS='|' read -r id name lab role mgmt br cidr; do
    [ -n "${id:-}" ] || continue
    if ct_exists "$id"; then
      st="$(pct status "$id" </dev/null 2>/dev/null | awk '{print $2}')"
      snap_present "$id" && snap=yes || snap=no
      if [ "$st" = "running" ]; then
        faults_live "$id" "$lab" "$role"; case $? in
          0) fl=armed ;; 1) fl=FIXED ;; *) fl=n/a ;;
        esac
        assert_mgmt_intact "$id" "$mgmt" >/dev/null 2>&1 && mg=OK || mg=BROKEN
      else fl=--; mg=--; fi
    else
      st=absent; snap=--; fl=--; mg=--
    fi
    printf '%-6s %-16s %-6s %-16s %-9s %-6s %-8s %s\n' "$id" "$name" "$lab" "$mgmt" "$st" "$snap" "$fl" "$mg"
  done <<< "$(spec_rows all)"
  printf '\nSSH: ssh fae@<MGMT_IP>   (reachable over Tailscale via the subnet route)\n\n'
}

# ---------------- main ----------------
cmd="${1:-}"; target="${2:-all}"
case "$cmd" in
  deploy)  validate_target "$target"; preflight "$target" full;  deploy_lab  "$target" ;;
  break)   validate_target "$target"; preflight "$target" light; break_lab   "$target" ;;
  reset)   validate_target "$target"; preflight "$target" light; reset_lab   "$target" ;;
  keys)    validate_target "$target"; preflight "$target" light; seed_keys   "$target" ;;
  destroy) validate_target "$target"; preflight "$target" light; destroy_lab "$target" ;;
  status)  preflight all light; status ;;
  *) usage; exit 1 ;;
esac
